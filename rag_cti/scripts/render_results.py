"""Render the README evaluation tables from the eval artifacts on disk.

The README's capability tables were previously hand-copied from JSON artifacts,
which drifts. This script reads the truth sources (capabilities_summary.json,
attribution_v3_results.json) and prints README-ready markdown — or rewrites the
README section between the RESULTS markers in place.

Usage:
    python scripts/render_results.py             # print markdown to stdout
    python scripts/render_results.py --write     # update ../README.md in place

The README section must be delimited by:
    <!-- CAPABILITY-RESULTS:BEGIN (generated by scripts/render_results.py) -->
    <!-- CAPABILITY-RESULTS:END -->
"""

from __future__ import annotations

# ruff: noqa: E402  (sys.path bootstrap before imports - run-without-install pattern)
import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).parent.parent / "src"))

from rag_cti.bootstrap import EVAL_DIR, PROJECT_ROOT

README = PROJECT_ROOT.parent / "README.md"
BEGIN = "<!-- CAPABILITY-RESULTS:BEGIN (generated by scripts/render_results.py) -->"
END = "<!-- CAPABILITY-RESULTS:END -->"


def _fmt(v: Any, digits: int = 4) -> str:
    if v is None:
        return "n/a"
    return f"{v:.{digits}f}" if isinstance(v, float) else str(v)


def render(summary: dict[str, Any], attribution: dict[str, Any] | None) -> str:
    caps = summary["capabilities_NEVER_averaged"]
    lines: list[str] = []

    lines.append("| Capability | Metric | Data | Result | Gate |")
    lines.append("|---|---|---|---|---|")

    tech = caps.get("technique_extraction", {})
    if "score" in tech:
        s = tech["score"]
        gate = tech.get("gate", {})
        lines.append(
            f"| technique extraction | Micro-F1(technique) | {tech.get('data', '')} "
            f"| **{_fmt(s.get('micro_f1'))}** (P={_fmt(s.get('precision'))} R={_fmt(s.get('recall'))}) "
            f"| >={gate.get('threshold')} -> {'PASS' if gate.get('pass') else 'FAIL'} |"
        )

    actor = caps.get("actor_attribution", {})
    if "score" in actor:
        s = actor["score"]
        gate = actor.get("gate", {})
        lines.append(
            f"| actor attribution | plausible / correct acc | {actor.get('data', '')} "
            f"| **{_fmt(s.get('plausible_acc'), 2)}** plausible ({_fmt(s.get('correct_acc'), 2)} correct; "
            f"C={s.get('C')} P={s.get('P')} I={s.get('I')}) "
            f"| >={gate.get('threshold')} -> {'PASS' if gate.get('pass') else 'FAIL'} |"
        )

    het = caps.get("heterogeneous_retrieval", {})
    if "set_metrics" in het:
        lines.append(
            f"| heterogeneous retrieval | set/hit@k per category | {het.get('data', '')} "
            "| see per-category below | — |"
        )

    gen = caps.get("generation_grounding", {})
    if "score" in gen:
        s = gen["score"]
        lines.append(
            f"| generation grounding | RAGAS faithfulness / answer_relevancy | {gen.get('data', '')} "
            f"| {_fmt(s.get('faithfulness'))} / {_fmt(s.get('answer_relevancy'))} | — |"
        )

    if attribution and attribution.get("results"):
        res = attribution["results"][0]
        by_cat = res.get("by_category", {})
        k_values = res.get("k_values", [])
        lines.append("")
        lines.append("**Heterogeneous retrieval — hit@k by category**")
        lines.append("")
        lines.append("| category | n | " + " | ".join(f"@{k}" for k in k_values) + " |")
        lines.append("|---|---|" + "---|" * len(k_values))
        for cat, m in by_cat.items():
            hits = m.get("hit_at_k", {})
            row = " | ".join(_fmt(hits.get(str(k), hits.get(k))) for k in k_values)
            lines.append(f"| {cat} | {m.get('n')} | {row} |")

        set_metrics = res.get("set_metrics") or {}
        prf_cats = {c: sm for c, sm in set_metrics.items() if "prf_at_k" in sm}
        if prf_cats:
            lines.append("")
            lines.append("**Multi-label set F1@k (technique-level, exact set)**")
            lines.append("")
            lines.append("| category | n | " + " | ".join(f"F1@{k}" for k in k_values) + " |")
            lines.append("|---|---|" + "---|" * len(k_values))
            for cat, sm in prf_cats.items():
                prf = sm["prf_at_k"]
                row = " | ".join(
                    _fmt((prf.get(str(k)) or prf.get(k) or {}).get("F1")) for k in k_values
                )
                lines.append(f"| {cat} | {sm.get('n')} | {row} |")

    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Render README eval tables from artifacts")
    parser.add_argument("--write", action="store_true", help="Rewrite README.md between markers")
    parser.add_argument("--summary", type=Path, default=EVAL_DIR / "capabilities_summary.json")
    parser.add_argument(
        "--attribution", type=Path, default=EVAL_DIR / "attribution_v3_results.json"
    )
    args = parser.parse_args()

    summary = json.loads(args.summary.read_text(encoding="utf-8"))
    attribution = (
        json.loads(args.attribution.read_text(encoding="utf-8"))
        if args.attribution.exists()
        else None
    )
    markdown = render(summary, attribution)

    if not args.write:
        print(markdown)
        return

    text = README.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        print(f"ERROR: README is missing the {BEGIN} / {END} markers.", file=sys.stderr)
        sys.exit(1)
    new_text = re.sub(
        re.escape(BEGIN) + r".*?" + re.escape(END),
        BEGIN + "\n" + markdown + "\n" + END,
        text,
        flags=re.DOTALL,
    )
    README.write_text(new_text, encoding="utf-8")
    print(f"Updated {README}")


if __name__ == "__main__":
    main()
